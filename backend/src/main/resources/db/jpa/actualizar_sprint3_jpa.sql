BEGIN;

CREATE TABLE IF NOT EXISTS rol (
  id_rol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(50) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS usuario (
  id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL, apellido VARCHAR(100),
  username VARCHAR(50) NOT NULL UNIQUE, password VARCHAR(255) NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE, id_rol BIGINT NOT NULL REFERENCES rol(id_rol),
  email VARCHAR(100) NOT NULL UNIQUE, email_verificado BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- En bases antiguas, el administrador debe completar el correo de cada cuenta heredada.
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS email VARCHAR(100);
CREATE UNIQUE INDEX IF NOT EXISTS usuario_email_unico_jpa ON usuario(email);
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS email_verificado BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP;

-- Sincronizar la secuencia antes de insertar roles en bases que tuvieron INSERT con ID manual.
SELECT setval(pg_get_serial_sequence('rol','id_rol'),COALESCE(MAX(id_rol),1),MAX(id_rol) IS NOT NULL) FROM rol;
INSERT INTO rol(nombre) SELECT 'ROLE_ADMIN' WHERE NOT EXISTS(SELECT 1 FROM rol WHERE nombre='ROLE_ADMIN');
INSERT INTO rol(nombre) SELECT 'ROLE_VENDEDOR' WHERE NOT EXISTS(SELECT 1 FROM rol WHERE nombre='ROLE_VENDEDOR');
INSERT INTO rol(nombre) SELECT 'ROLE_CLIENTE' WHERE NOT EXISTS(SELECT 1 FROM rol WHERE nombre='ROLE_CLIENTE');
-- Los roles obsoletos pasan a CLIENTE, sin conceder permisos de personal.
UPDATE usuario SET id_rol=(SELECT id_rol FROM rol WHERE nombre='ROLE_CLIENTE')
WHERE id_rol IN (SELECT id_rol FROM rol WHERE UPPER(TRIM(nombre)) IN ('ROLE_PROVEEDOR','PROVEEDOR','ROLE_ALMACENERO','ALMACENERO'));
DELETE FROM rol WHERE UPPER(TRIM(nombre)) IN ('ROLE_PROVEEDOR','PROVEEDOR','ROLE_ALMACENERO','ALMACENERO');

CREATE TABLE IF NOT EXISTS categoria (
  id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL, descripcion VARCHAR(255), activo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS producto (
  id_producto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(50) NOT NULL UNIQUE, nombre VARCHAR(150) NOT NULL, descripcion VARCHAR(255),
  precio NUMERIC(12,2) NOT NULL CHECK(precio>=0), activo BOOLEAN NOT NULL DEFAULT TRUE,
  id_categoria BIGINT NOT NULL REFERENCES categoria(id_categoria)
);
CREATE TABLE IF NOT EXISTS stock (
  id_stock BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_producto BIGINT NOT NULL REFERENCES producto(id_producto),
  cantidad INTEGER NOT NULL DEFAULT 0 CHECK(cantidad>=0),
  stock_minimo INTEGER NOT NULL DEFAULT 30 CHECK(stock_minimo>=0)
);
CREATE UNIQUE INDEX IF NOT EXISTS stock_producto_unico ON stock(id_producto);
CREATE TABLE IF NOT EXISTS movimiento_inventario (
  id_movimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_producto BIGINT NOT NULL REFERENCES producto(id_producto),
  id_usuario BIGINT REFERENCES usuario(id_usuario), tipo VARCHAR(10) NOT NULL,
  cantidad INTEGER NOT NULL CHECK(cantidad>0), fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  descripcion VARCHAR(250), stock_anterior INTEGER, stock_nuevo INTEGER
);
ALTER TABLE movimiento_inventario ADD COLUMN IF NOT EXISTS stock_anterior INTEGER;
ALTER TABLE movimiento_inventario ADD COLUMN IF NOT EXISTS stock_nuevo INTEGER;

CREATE TABLE IF NOT EXISTS auth_challenges (
  id UUID PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES usuario(id_usuario),
  code_hash VARCHAR(255) NOT NULL, purpose VARCHAR(10) NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0, used BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, expires_at TIMESTAMP NOT NULL
);
-- Los códigos pendientes se invalidan al migrar la autenticación.
UPDATE auth_challenges SET used=TRUE WHERE used=FALSE;
-- Corregir el enlace antiguo a users(id) si estaba presente.
ALTER TABLE auth_challenges DROP CONSTRAINT IF EXISTS auth_challenges_user_id_fkey;
ALTER TABLE auth_challenges DROP CONSTRAINT IF EXISTS fk_auth_usuario;
DELETE FROM auth_challenges a WHERE NOT EXISTS(SELECT 1 FROM usuario u WHERE u.id_usuario=a.user_id);
ALTER TABLE auth_challenges ADD CONSTRAINT fk_auth_usuario FOREIGN KEY(user_id) REFERENCES usuario(id_usuario);
CREATE INDEX IF NOT EXISTS auth_challenges_user_time_jpa ON auth_challenges(user_id,created_at);

CREATE TABLE IF NOT EXISTS verificacion_email (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL,
  codigo_hash VARCHAR(255) NOT NULL, fecha_expiracion TIMESTAMP NOT NULL,
  intentos INTEGER NOT NULL DEFAULT 0, usado BOOLEAN NOT NULL DEFAULT FALSE,
  fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS venta (
  id_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, total NUMERIC(12,2) NOT NULL,
  id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario),
  id_cliente BIGINT REFERENCES usuario(id_usuario),
  metodo_pago VARCHAR(20) NOT NULL DEFAULT 'EN_TIENDA',
  estado VARCHAR(20) NOT NULL DEFAULT 'REGISTRADA'
);
ALTER TABLE venta ADD COLUMN IF NOT EXISTS id_cliente BIGINT REFERENCES usuario(id_usuario);
ALTER TABLE venta ADD COLUMN IF NOT EXISTS metodo_pago VARCHAR(20) NOT NULL DEFAULT 'EN_TIENDA';
ALTER TABLE venta ADD COLUMN IF NOT EXISTS estado VARCHAR(20) NOT NULL DEFAULT 'REGISTRADA';
CREATE INDEX IF NOT EXISTS venta_cliente_fecha_jpa ON venta(id_cliente,fecha);
CREATE TABLE IF NOT EXISTS detalle_venta (
  id_detalle_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_venta BIGINT NOT NULL REFERENCES venta(id_venta), id_producto BIGINT NOT NULL REFERENCES producto(id_producto),
  cantidad INTEGER NOT NULL CHECK(cantidad>0), precio_unitario NUMERIC(12,2) NOT NULL,
  subtotal NUMERIC(12,2) NOT NULL
);
CREATE TABLE IF NOT EXISTS compra (
  id_compra BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, total NUMERIC(12,2) NOT NULL,
  id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario), referencia_proveedor VARCHAR(200)
);
ALTER TABLE compra ADD COLUMN IF NOT EXISTS referencia_proveedor VARCHAR(200);
CREATE TABLE IF NOT EXISTS detalle_compra (
  id_detalle_compra BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_compra BIGINT NOT NULL REFERENCES compra(id_compra), id_producto BIGINT NOT NULL REFERENCES producto(id_producto),
  cantidad INTEGER NOT NULL CHECK(cantidad>0), precio_unitario NUMERIC(12,2) NOT NULL,
  subtotal NUMERIC(12,2) NOT NULL
);

-- Contrato del carrito del frontend fusionado: importes calculados en servidor.
ALTER TABLE venta ADD COLUMN IF NOT EXISTS subtotal NUMERIC(12,2);
ALTER TABLE venta ADD COLUMN IF NOT EXISTS descuento NUMERIC(12,2) NOT NULL DEFAULT 0;
ALTER TABLE venta ADD COLUMN IF NOT EXISTS cliente_nombre VARCHAR(200);
ALTER TABLE venta ADD COLUMN IF NOT EXISTS vendedor_nombre VARCHAR(200);
UPDATE venta SET subtotal = total + descuento WHERE subtotal IS NULL;
ALTER TABLE venta ALTER COLUMN subtotal SET NOT NULL;
ALTER TABLE venta ALTER COLUMN estado SET DEFAULT 'COMPLETED';
UPDATE venta SET estado='COMPLETED' WHERE estado IN ('REGISTRADA','PENDIENTE_RETIRO');
UPDATE venta v SET vendedor_nombre=CONCAT_WS(' ',u.nombre,u.apellido)
FROM usuario u WHERE u.id_usuario=v.id_usuario AND v.vendedor_nombre IS NULL;
UPDATE venta v SET cliente_nombre=CONCAT_WS(' ',u.nombre,u.apellido)
FROM usuario u WHERE u.id_usuario=v.id_cliente AND v.cliente_nombre IS NULL;
-- Guardar nombre y código del producto en el detalle conserva el historial.
ALTER TABLE detalle_venta ADD COLUMN IF NOT EXISTS producto_nombre VARCHAR(150);
ALTER TABLE detalle_venta ADD COLUMN IF NOT EXISTS producto_codigo VARCHAR(50);
UPDATE detalle_venta d SET producto_nombre=p.nombre FROM producto p
WHERE d.id_producto=p.id_producto AND d.producto_nombre IS NULL;
UPDATE detalle_venta d SET producto_codigo=p.codigo FROM producto p
WHERE d.id_producto=p.id_producto AND d.producto_codigo IS NULL;
ALTER TABLE detalle_compra ADD COLUMN IF NOT EXISTS producto_nombre VARCHAR(150);
ALTER TABLE detalle_compra ADD COLUMN IF NOT EXISTS producto_codigo VARCHAR(50);
UPDATE detalle_compra d SET producto_nombre=p.nombre FROM producto p
WHERE d.id_producto=p.id_producto AND d.producto_nombre IS NULL;
UPDATE detalle_compra d SET producto_codigo=p.codigo FROM producto p
WHERE d.id_producto=p.id_producto AND d.producto_codigo IS NULL;
CREATE INDEX IF NOT EXISTS venta_fecha_jpa ON venta(fecha);
CREATE INDEX IF NOT EXISTS compra_fecha_jpa ON compra(fecha);
COMMIT;
