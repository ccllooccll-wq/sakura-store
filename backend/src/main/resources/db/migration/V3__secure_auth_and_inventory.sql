CREATE TABLE auth_challenges (
 id UUID PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 code_hash VARCHAR(255) NOT NULL, purpose VARCHAR(10) NOT NULL CHECK(purpose IN ('LOGIN','REGISTER','RESET')),
 attempts INTEGER NOT NULL DEFAULT 0, used BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, expires_at TIMESTAMP NOT NULL
);
CREATE INDEX auth_challenges_user_time ON auth_challenges(user_id,created_at);
CREATE TABLE inventory_categories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL UNIQUE
);
CREATE TABLE inventory_products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sku VARCHAR(50) NOT NULL UNIQUE, name VARCHAR(150) NOT NULL,
 category_id BIGINT NOT NULL REFERENCES inventory_categories(id),
 price NUMERIC(12,2) NOT NULL CHECK(price>=0), min_stock INTEGER NOT NULL DEFAULT 0 CHECK(min_stock>=0),
 stock INTEGER NOT NULL DEFAULT 0 CHECK(stock>=0), active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE inventory_movements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id BIGINT NOT NULL REFERENCES inventory_products(id),
 type VARCHAR(10) NOT NULL CHECK(type IN ('ENTRADA','SALIDA')),
 quantity INTEGER NOT NULL CHECK(quantity>0), previous_stock INTEGER NOT NULL CHECK(previous_stock>=0),
 new_stock INTEGER NOT NULL CHECK(new_stock>=0), reason VARCHAR(250) NOT NULL,
 actor_id BIGINT REFERENCES users(id) ON DELETE SET NULL, actor_name VARCHAR(100) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX inventory_movements_product ON inventory_movements(product_id,created_at);
